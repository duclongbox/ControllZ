#pragma once

#include <cstdint>
#include <optional>
#include <string>
#include <string_view>

#include "desktophost/input/input_injector.h"

namespace desktophost {

enum class PointerAction { move, delta, down, up, scroll };

/// One parsed message from `shared/schemas/input/`.
///
/// Every field is absolute: the position the event happened at, and the full
/// button mask as of that event. Nothing here is a delta, so no message
/// depends on another having arrived — which is the only way to survive an
/// unordered, unreliable channel. The two exceptions carry distance rather
/// than state (`scroll`, and game mode's `delta`), and deltas commute: a lost
/// one costs that much travel, never a wrong position.
struct PointerMessage {
    PointerAction action = PointerAction::move;

    /// Monotonic across *all* pointer messages on the channel, not per type.
    /// The router relies on that: a move older than the newest button
    /// transition has to be droppable, or a late `buttons: 0` move undoes a
    /// press that already happened.
    uint32_t seq = 0;

    /// Sender's `Date.now()`. Diagnostics only — the clocks are unsynchronised,
    /// so this must never be used for ordering.
    int64_t sentAtMs = 0;

    double nx = 0;
    double ny = 0;

    /// Buttons held after this event.
    uint8_t buttons = 0;

    /// Meaningful for `down` and `up`; left alone for a move.
    MouseButton button = MouseButton::left;

    /// 1 single, 2 double, 3 triple. Decided by the phone.
    int clickCount = 1;

    /// `scroll`: the sender's CSS pixels, DOM signs (positive dy scrolls
    /// down), one wheel notch = 100 — see `shared/schemas/input/scroll.schema.json`
    /// for why a delta is safe here. `delta`: travel as a fraction of the
    /// frame, positive right/down, scaled to pixels against the display at
    /// injection (`pointerDelta.schema.json`). Unused for anything else.
    double dx = 0;
    double dy = 0;

    /// `down`, `up` and `scroll`: act at the host's current cursor position
    /// instead of moving to nx/ny first. Game mode sends this because the
    /// cursor has been moved by deltas and the phone no longer knows where it
    /// is — and because the positioning move would be read as a camera jump.
    bool inPlace = false;
};

/// One parsed message from the `keys` channel (`shared/schemas/input/key.schema.json`).
///
/// Unlike a pointer message this is an *event*, not a state: the `keys` channel
/// is ordered and reliable, so every keystroke arrives exactly once and in the
/// order it was typed — which is the whole reason it has a channel of its own.
struct KeyMessage {
    bool down = true;
    /// DOM `KeyboardEvent.code`: a physical position, never a character.
    std::string code;
    /// An autorepeat from a held key, generated by the *sender's* OS. Neither
    /// host autorepeats a synthesised key on its own, so these are what make a
    /// held Backspace keep deleting.
    bool repeat = false;
    int64_t sentAtMs = 0;
};

/// Parses one `keys`-channel message. Nullopt for anything malformed — the
/// same untrusted-peer rule as the pointer parser.
std::optional<KeyMessage> parseKeyMessage(std::string_view json);

/// A run of characters to type (`shared/schemas/input/text.schema.json`),
/// from the phone's on-screen keyboard. The one keyboard message that carries
/// characters rather than positions, decoded to UTF-16 here because both
/// injection APIs (CGEventKeyboardSetUnicodeString, KEYEVENTF_UNICODE) take
/// UTF-16 units.
struct TextMessage {
    std::u16string text;
    int64_t sentAtMs = 0;
};

/// The schema's bound on one `text` message, in code points. A longer run is
/// split by the phone; one past this is a sender to refuse, not to clamp.
constexpr size_t kMaxTextCodePoints = 1024;

/// Parses one `text` message. Nullopt for anything malformed: not ours,
/// empty, over the bound, invalid UTF-8, or containing a control character
/// (Enter and Backspace travel as key events, never inside text).
std::optional<TextMessage> parseTextMessage(std::string_view json);

/// Strict UTF-8 → UTF-16. Nullopt on any malformed sequence — overlong forms,
/// surrogate code points, truncation, bytes above U+10FFFF — rather than a
/// replacement character, because text from a remote peer that is not valid
/// UTF-8 is a sender to refuse. Portable, so it is tested on every platform.
std::optional<std::u16string> utf8ToUtf16(std::string_view utf8);

/// Which family of shortcuts the desktop answers to
/// (`shared/schemas/input/hostInfo.schema.json`). `mac` is the Command family;
/// the other two are the Control family.
enum class HostPlatform { windows, mac, linux };

/// The platform this binary was built for.
HostPlatform currentHostPlatform();

/// The wire name of a platform: "windows", "mac" or "linux".
std::string_view hostPlatformName(HostPlatform platform);

/// The `hostInfo` message the host sends the phone once, on the `keys`
/// channel, as soon as it opens. The one message that travels desktop -> phone
/// on an input channel: it lets the phone translate Cmd <-> Ctrl before
/// sending, so the host itself never has to remap a key.
std::string encodeHostInfo(HostPlatform platform);

/// Parses one input-channel message. Returns nullopt for anything malformed,
/// unknown, or out of range — a remote peer is untrusted input, and the router
/// counts a rejection rather than acting on a guess.
std::optional<PointerMessage> parsePointerMessage(std::string_view json);

}  // namespace desktophost
